export function resolveIcon(name: string): TablerIcon {
  if (name in icons) return icons[name as IconName];
  const mapped = legacyNames[name] ?? categoryFallbacks[name.split('/')[0]] ?? 'view';
  return icons[mapped];
}

export function normalizeIconSize(size: number): 16 | 20 | 24 | 32 | 40 | 48 {
  if (size <= 17) return 16;
  if (size <= 21) return 20;
  if (size <= 27) return 24;
  if (size <= 35) return 32;
  if (size <= 43) return 40;
  return 48;
}
